test("opencode: a .opencode or .opencode/agents that is a link is not used: nothing is written, swept or removed through it, and it is said", async () => {
  for (const link of [".opencode", ".opencode/agents"]) {
    const cwd = tmp();
    const outside = tmp();
    writeAgentFiles({ dir: path.join(outside, "agents"), definitions: [def("stale")] });
    if (link === ".opencode") fs.symlinkSync(outside, path.join(cwd, ".opencode"));
    else {
      fs.mkdirSync(path.join(cwd, ".opencode"));
      fs.symlinkSync(path.join(outside, "agents"), path.join(cwd, ".opencode/agents"));
    }
    const before = fs.readdirSync(path.join(outside, "agents")).sort();
    const errors = [];
    const rec = spawnRecorder();
    rec.spawnFn.during = () => fs.readdirSync(path.join(outside, "agents")).sort();
    await launchOpencode({ prompt: "x", config: {}, state: idle, projectDir: cwd, subagents: [def("scout")], spawnFn: rec.spawnFn, tmpDir: tmp(), stderr: { write: (s) => errors.push(s) } });
    assert.deepEqual(rec.calls[0].during, before, `${link}: nothing is written there while the session runs`);
    assert.deepEqual(fs.readdirSync(path.join(outside, "agents")).sort(), before, link);
    assert.match(errors.join(""), /subagents were not registered: .*is a symlink or not a folder/, link);
  }
});

