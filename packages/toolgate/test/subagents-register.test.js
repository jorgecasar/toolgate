test("claude: the tools are the allowlist (the declared ones or the read-only default), servers are mcp__<server>, the prompt carries the NEEDS line", () => {
  const agents = claudeAgents([def("scout"), def("review", { tools: ["Read", "Bash"], mcps: ["github"], model: "sonnet" })]);
  assert.deepEqual(agents.scout.tools, ["Read", "Grep", "Glob"]);
  assert.deepEqual(agents.review.tools, ["Read", "Bash", "mcp__github"]);
  assert.equal(agents.review.model, "sonnet");
  assert.equal("model" in agents.scout, false);
  assert.ok(agents.scout.prompt.startsWith("You are scout.") && agents.scout.prompt.endsWith(NEEDS_INSTRUCTION));
  assert.match(NEEDS_INSTRUCTION, /`NEEDS: <tool or server> - <reason>`/);
  assert.doesNotMatch(JSON.stringify(agents), /permissionMode|hooks|mcpServers/);
});

test("opencode: every gated tool the definition does not list is denied, the servers it needs are allowed, and the file is marked", () => {
  const text = opencodeAgentFile(def("scout"), "<!-- generated by toolgate for this session: x -->");
  const permission = JSON.parse(text.match(/^permission: (.*)$/m)[1]);
  assert.deepEqual(Object.entries(permission).filter(([, v]) => v === "allow").map(([k]) => k).sort(), ["glob", "grep", "list", "read"], "only what it lists is allowed");
  assert.equal(Object.keys(permission)[0], "*");
  assert.equal(permission["*"], "deny", "everything not listed is denied first");
  assert.equal(permission.edit, "deny");
  assert.equal(permission.bash, "deny");
  assert.match(text, /^mode: subagent$/m);
  const wide = JSON.parse(opencodeAgentFile(def("w", { tools: ["Bash", "Write"], mcps: ["github"] }), "m").match(/^permission: (.*)$/m)[1]);
  assert.deepEqual([wide.bash, wide.edit, wide.read, wide["github_*"]], ["allow", "allow", "deny", "allow"]);
  assert.match(text, /generated by toolgate for this session/);
  assert.ok(text.endsWith(`${NEEDS_INSTRUCTION}\n`));
});

test("marked files: written, a foreign file or a link is never touched, removal and the sweep take only toolgate's own", () => {
  const dir = path.join(tmp(), ".opencode/agents");
  put(dir, "mine.md", "my own subagent\n");
  const outside = tmp();
  put(outside, "target.md", "victim");
  fs.symlinkSync(path.join(outside, "target.md"), path.join(dir, "linked.md"));
  const result = writeAgentFiles({ dir, definitions: [def("mine"), def("linked"), def("new")] });
  assert.deepEqual(result.written.map((f) => path.basename(f)), ["new.md"]);
  assert.deepEqual(result.skipped.map((s) => s.name).sort(), ["linked", "mine"]);
  assert.equal(fs.readFileSync(path.join(dir, "mine.md"), "utf8"), "my own subagent\n");
  assert.equal(fs.readFileSync(path.join(outside, "target.md"), "utf8"), "victim");
  assert.match(fs.readFileSync(path.join(dir, "new.md"), "utf8"), /generated by toolgate for this session/);

  // a file that lost its marker (the user took it over) is not removed
  fs.writeFileSync(path.join(dir, "new.md"), "taken over");
  result.remove();
  assert.equal(fs.readFileSync(path.join(dir, "new.md"), "utf8"), "taken over");
  writeAgentFiles({ dir: path.join(dir, "..", "other"), definitions: [def("a")] });
  removeAgentFiles([path.join(dir, "..", "other", "a.md")]);
  assert.ok(!fs.existsSync(path.join(dir, "..", "other", "a.md")));

  const sweep = path.join(tmp(), "agents");
  writeAgentFiles({ dir: sweep, definitions: [def("left")] });
  put(sweep, "keep.md", "not ours");
  put(sweep, "notes.txt", "x");
  assert.deepEqual(sweepAgentFiles({ dir: sweep }).map((f) => path.basename(f)), ["left.md"]);
  assert.deepEqual(fs.readdirSync(sweep).sort(), ["keep.md", "notes.txt"]);
  assert.deepEqual(sweepAgentFiles({ dir: path.join(sweep, "missing") }), []);
});

test("the subagents capability: every adapter declares the table's value, and a bad value names the field", () => {
  const base = Object.freeze({ defersToolSchemas: false, rules: { kind: "none" }, launchGating: "none", exclusiveMcpConfig: false, resume: { supported: false }, dynamicTools: false, passthrough: "args" });
  const problem = (subagents) => validateCapability(Object.freeze({ ...base, subagents })).join("; ");
  assert.equal(problem(undefined), "");
  for (const good of [{ kind: "none" }, { kind: "unknown" }, { kind: "launchFlag", flag: "--agents" }, { kind: "projectDir", dialect: "opencode", dir: ".opencode/agents" }]) assert.equal(problem(good), "", JSON.stringify(good));
  assert.match(problem(null), /subagents must be an object/);
  assert.match(problem({ kind: "x" }), /subagents.kind must be one of/);
  assert.match(problem({ kind: "none", flag: "--agents" }), /does not take "flag"/);
  assert.match(problem({ kind: "launchFlag", flag: "agents" }), /must be a command-line flag/);
  assert.match(problem({ kind: "launchFlag", flag: "--a b" }), /must be a command-line flag/);
  assert.match(problem({ kind: "projectDir", dialect: "opencode", dir: "../x" }), /relative folder inside the project/);
  assert.match(problem({ kind: "projectDir", dialect: "vim", dir: "a" }), /dialect must be claude or opencode/);
  assert.match(problem({ kind: "projectDir", dialect: "claude", dir: "a", flag: "--x" }), /does not take "flag"/);
  return Promise.all(defaultRegistry.names().map(async (name) => assert.equal((await defaultRegistry.get(name)).capability.subagents, SUBAGENTS_CAPABILITY[name], name)));
});

function spawnRecorder() {
  const calls = [];
  const spawnFn = (cmd, args, opts) => {
    const child = new EventEmitter();
    calls.push({ cmd, args, opts, during: spawnFn.during?.() });
    queueMicrotask(() => child.emit("exit", 0, null));
    return child;
  };
  return { calls, spawnFn };
}
const claudeIo = (extra = {}) => ({ readFileFn: () => JSON.stringify({ mcpServers: {} }), writeFileFn: () => {}, tmpDir: "/tmp", config: {}, state: idle, ...extra });

test("claude: --agents carries the active subagents before the prompt; none active, no flag", async () => {
  const withAgents = spawnRecorder();
  await launchClaude({ prompt: "do it", subagents: [def("scout")], spawnFn: withAgents.spawnFn, ...claudeIo() });
  const args = withAgents.calls[0].args;
  assert.equal(args[args.length - 1], "do it");
  const given = JSON.parse(args[args.indexOf("--agents") + 1]);
  assert.deepEqual(Object.keys(given), ["scout"]);
  const none = spawnRecorder();
  await launchClaude({ prompt: "do it", subagents: [], spawnFn: none.spawnFn, ...claudeIo() });
  assert.equal(none.calls[0].args.includes("--agents"), false);
});

test("claude passthrough: the user's own --agents is merged (theirs win), a file is left alone and ours are not added, other arguments stay", async () => {
  const merged = spawnRecorder();
  await launchClaude(["--model", "opus", "--agents", JSON.stringify({ scout: { description: "mine", prompt: "mine" }, extra: { description: "e", prompt: "p" } }), "-p", "go"], { subagents: [def("scout"), def("other")], spawnFn: merged.spawnFn, ...claudeIo() });
  const args = merged.calls[0].args;
  assert.equal(args.filter((a) => a === "--agents").length, 1);
  const given = JSON.parse(args[args.indexOf("--agents") + 1]);
  assert.deepEqual(Object.keys(given).sort(), ["extra", "other", "scout"]);
  assert.equal(given.scout.prompt, "mine", "the user's definition wins on a clash");
  assert.ok(args.includes("--model") && args.includes("opus") && args.includes("-p") && args.includes("go"));

  const errors = [];
  const file = spawnRecorder();
  await launchClaude(["--agents", "/some/agents.json"], { subagents: [def("scout")], spawnFn: file.spawnFn, stderr: { write: (s) => errors.push(s) }, ...claudeIo() });
  assert.equal(file.calls[0].args.filter((a) => a === "--agents").length, 1);
  assert.ok(file.calls[0].args.includes("/some/agents.json"));
  assert.match(errors.join(""), /your own --agents is not inline JSON, so the active subagents were not added/);

  const plain = spawnRecorder();
  await launchClaude(["-p", "go"], { subagents: [def("scout")], spawnFn: plain.spawnFn, ...claudeIo() });
  assert.ok(plain.calls[0].args.includes("--agents"));
  const raw = spawnRecorder();
  await launchClaude(["mcp", "list"], { raw: true, subagents: [def("scout")], spawnFn: raw.spawnFn, ...claudeIo() });
  assert.deepEqual(raw.calls[0].args, ["mcp", "list"], "a subcommand of the agent is run as it is");
});

test("opencode: the files exist while the session runs and are gone after it; a leftover is swept; a user's file stays", async () => {
  const cwd = tmp();
  put(cwd, ".opencode/agents/mine.md", "my own\n");
  writeAgentFiles({ dir: path.join(cwd, ".opencode/agents"), definitions: [def("left")] });
  const rec = spawnRecorder();
  rec.spawnFn.during = () => fs.readdirSync(path.join(cwd, ".opencode/agents")).sort();
  const errors = [];
  const result = await launchOpencode({ prompt: "x", config: {}, state: idle, projectDir: cwd, subagents: [def("scout"), def("mine")], spawnFn: rec.spawnFn, tmpDir: tmp(), stderr: { write: (s) => errors.push(s) } });
  assert.deepEqual(rec.calls[0].during, ["mine.md", "scout.md"], "the leftover is gone, the user's file and the new one are there");
  assert.deepEqual(fs.readdirSync(path.join(cwd, ".opencode/agents")), ["mine.md"]);
  assert.equal(fs.readFileSync(path.join(cwd, ".opencode/agents/mine.md"), "utf8"), "my own\n");
  assert.match(errors.join(""), /subagent mine was not registered: a file of that name is already there and toolgate did not write it/);
  assert.deepEqual(result.subagents.map((f) => path.basename(f)), ["scout.md"]);

  const none = await launchOpencode({ prompt: "x", config: {}, state: idle, projectDir: cwd, subagents: [], spawnFn: spawnRecorder().spawnFn, tmpDir: tmp() });
  assert.deepEqual(none.subagents, []);
});

test("need records a subagent for the next launch once, and says so; an agent that cannot register them records nothing", () => {
  const routed = { servers: [], alwaysOn: [], missing: [], skills: [], commands: [], subagents: [{ name: "review", path: "/p", tools: ["Read"], toolsDefault: false, score: 1, snippet: "" }], warnings: [], binding: null };
  const adapter = { capability: { subagents: SUBAGENTS_CAPABILITY["claude-code"] }, supportsResume: true };
  const first = resolveNeed(routed, { state: idle, agent: "claude-code", adapter });
  assert.deepEqual([first.state.subagentExtras, first.state.pendingRestart], [["review"], true]);
  assert.match(first.result.restart, /end the session/);
  assert.match(formatNeed(first.result), /^subagent review: registered at the next launch, not in this session \(tools it would get: Read\)/m);
  const again = resolveNeed(routed, { state: first.state, agent: "claude-code", adapter });
  assert.equal(again.state, null, "asking again records nothing new");

  const codex = resolveNeed(routed, { state: idle, agent: "codex", adapter: { capability: { subagents: SUBAGENTS_CAPABILITY.codex } } });
  assert.equal(codex.state, null);
  assert.equal(codex.result.restart, null);
  assert.match(formatNeed(codex.result), /^subagent review: this agent cannot register subagents, so it is not available/m);
});

test("the launch registers the baseline and the escalated subagents, says what it cannot find, and registers none for an adapter that cannot", async () => {
  const cwd = tmp();
  put(cwd, ".toolgate/subagents/base.md", "---\ndescription: Base one\n---\nBase.\n");
  put(cwd, ".toolgate/subagents/later.md", "---\ndescription: Later one\n---\nLater.\n");
  const launches = [];
  const make = (kind) => ({ capability: { subagents: { kind } }, launch: (options) => (launches.push(options), Promise.resolve({ code: 0 })) });
  const errors = [];
  const deps = (adapter, state) => ({
    cwd,
    stdout: { write: () => {} },
    stderr: { write: (s) => errors.push(s) },
    env: { TOOLGATE_ADAPTER: "claude-code", HOME: cwd, TOOLGATE_DEFAULTS: path.join(cwd, "none.json") },
    loadConfigFn: () => ({ subagents: { baseline: ["base", "ghost"] } }),
    loadStateFn: () => state,
    saveStateFn: () => {},
    adapters: { "claude-code": () => Promise.resolve(adapter) },
  });
  await run(["--no-route", "go"], deps(make("launchFlag"), { ...idle, subagentExtras: ["later"], pendingRestart: true }));
  assert.deepEqual(launches[0].subagents.map((s) => s.name), ["base", "later"]);
  assert.equal(launches[0].projectDir, cwd);
  assert.match(errors.join(""), /subagents not found in the sources, so not registered: ghost/);
  await run(["--no-route", "go"], deps(make("unknown"), idle));
  assert.deepEqual(launches[1].subagents, []);
});

