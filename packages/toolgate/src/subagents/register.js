// Registering subagents in an agent at launch. An agent only knows a subagent that is in its configuration, and every
// registered one adds its description to the context, so toolgate registers only the active set: the baseline of the
// config, the ones `route` found for the launch prompt, and the ones an earlier `need` asked for. What is registered
// is the neutral definition: the tools it lists or the read-only default, never more, plus the servers it needs.
import fs from "node:fs";
import path from "node:path";
import { hasDescription } from "../assets/common.js";
import { linkedPart } from "../commands/bridge.js";
import { settings as skillsSettings } from "../skills/cli.js";
import { scanSubagents } from "../skills/scan.js";
import { DEFAULT_SUBAGENT_TOOLS } from "./parse.js";

/** Added to the prompt of every registered subagent: the way to ask for what it lacks is text for the agent that invoked it. */
export const NEEDS_INSTRUCTION =
  "If you need a tool or an MCP server you were not given, do not try to work around it: end your answer with one line `NEEDS: <tool or server> - <reason>`. The agent that invoked you will ask the user.";

/** The names of the subagents to register: baseline, found for the prompt, and escalated (once a restart is pending). */
export function activeSubagentNames({ config, state, routed }) {
  const names = new Set(config?.subagents?.baseline ?? []);
  for (const subagent of routed?.subagents ?? []) names.add(subagent.name);
  if (state?.pendingRestart) for (const name of state.subagentExtras ?? []) names.add(name);
  return names;
}

/**
 * The definitions to register, read from the subagent sources. A name that is not found is reported, not guessed.
 * @returns {{ definitions: object[], missing: string[] }}
 */
export function activeSubagents({ config, state, routed, cwd, env }) {
  const names = activeSubagentNames({ config, state, routed });
  if (names.size === 0) return { definitions: [], missing: [] };
  const found = new Map(scanSubagents(skillsSettings(config, cwd, env).subagentSources).map((subagent) => [subagent.name, subagent]));
  return { definitions: [...names].filter((name) => found.has(name)).sort().map((name) => found.get(name)), missing: [...names].filter((name) => !found.has(name)).sort() };
}

const prompt = (definition) => `${definition.prompt}\n\n${NEEDS_INSTRUCTION}`;
const tools = (definition) => [...(definition.tools ?? DEFAULT_SUBAGENT_TOOLS)];

/** Claude Code: the JSON for `--agents`. Tools are the allowlist, and each server it needs is listed as `mcp__<server>`. */
export function claudeAgents(definitions) {
  const agents = {};
  for (const definition of definitions) {
    agents[definition.name] = {
      // A subagent without a description (accepted, and reported by `doctor`) gets no `description` key, not an empty one.
      ...(hasDescription(definition) ? { description: definition.description } : {}),
      prompt: prompt(definition),
      tools: [...tools(definition), ...(definition.mcps ?? []).map((server) => `mcp__${server}`)],
      ...(definition.model ? { model: definition.model } : {}),
    };
  }
  return agents;
}

// Claude's tool names as opencode's permission keys.
const OPENCODE_KEY = { Read: "read", Grep: "grep", Glob: "glob", Edit: "edit", Write: "edit", MultiEdit: "edit", NotebookEdit: "edit", Bash: "bash", WebFetch: "webfetch", WebSearch: "websearch", Task: "task", Skill: "skill" };
const OPENCODE_GATED = ["read", "grep", "glob", "list", "edit", "bash", "webfetch", "websearch", "task", "lsp", "skill"];

/** opencode: the file for `.opencode/agents/<name>.md`; every gated tool the definition does not list is denied. */
export function opencodeAgentFile(definition, marker = markerLine) {
  const allowed = new Set(tools(definition).map((tool) => OPENCODE_KEY[tool]).filter(Boolean));
  if (allowed.has("read") || allowed.has("grep") || allowed.has("glob")) allowed.add("list");
  const permission = Object.fromEntries([
    // Everything is denied first, so a tool or a server that is not listed cannot be reached through the user's own permissions.
    ["*", "deny"],
    ...OPENCODE_GATED.map((key) => [key, allowed.has(key) ? "allow" : "deny"]),
    // opencode names the tools of a server `<server>_<tool>`; this key format is not verified against its documentation,
    // and with the deny above a wrong key can only deny.
    ...(definition.mcps ?? []).map((server) => [`${server}_*`, "allow"]),
  ]);
  const head = ["---", ...(hasDescription(definition) ? [`description: ${JSON.stringify(definition.description)}`] : []), "mode: subagent", ...(definition.model ? [`model: ${JSON.stringify(definition.model)}`] : []), `permission: ${JSON.stringify(permission)}`, "---", ""];
  return [...head, marker, "", prompt(definition), ""].join("\n");
}

const markerLine = "<!-- generated by toolgate for this session: it is removed when the session ends -->";

/** `dir` (relative to the project) when no part of it is a link: a link could lead outside the project. Returns the part that is one, or null. */
export const linkInPath = (projectDir, dir) => linkedPart(projectDir, dir.split(path.sep).join("/"));

/**
 * Writes the files of the definitions into `dir`. A file that is already there and was not written by toolgate is never
 * touched: that name is skipped and reported. Returns what was written, to be removed afterwards.
 * @returns {{ written: string[], skipped: Array<{ name: string, reason: string }>, remove: () => void }}
 */
export function writeAgentFiles({ dir, definitions, fsApi = fs }) {
  const written = [];
  const skipped = [];
  for (const definition of definitions) {
    const file = path.join(dir, `${definition.name}.md`);
    const info = (() => {
      try {
        return fsApi.lstatSync(file);
      } catch {
        return null;
      }
    })();
    if (info && (info.isSymbolicLink() || !info.isFile() || !isOurs(fsApi, file))) {
      skipped.push({ name: definition.name, reason: "a file of that name is already there and toolgate did not write it" });
      continue;
    }
    fsApi.mkdirSync(dir, { recursive: true });
    const temp = `${file}.${process.pid}.tmp`;
    fsApi.rmSync(temp, { force: true });
    fsApi.writeFileSync(temp, opencodeAgentFile(definition, markerLine), { flag: "wx" });
    fsApi.renameSync(temp, file);
    written.push(file);
  }
  return { written, skipped, remove: () => removeAgentFiles(written, fsApi) };
}

/** Removes the files toolgate wrote, and only those: one that lost its marker is left. */
export function removeAgentFiles(files, fsApi = fs) {
  for (const file of files) {
    if (isOurs(fsApi, file)) fsApi.rmSync(file, { force: true });
  }
}

/** Whether `file` is a regular file with the marker that `writeAgentFiles` puts in it (a symlink is never ours). */
export function isOurs(fsApi, file) {
  try {
    const info = fsApi.lstatSync(file);
    if (!info.isFile() || info.size >= 256 * 1024) return false;
    // The exact marker line, where `opencodeAgentFile` puts it: two lines after the end of the frontmatter. A phrase
    // somewhere in a note of the user's does not make it ours.
    const lines = fsApi.readFileSync(file, "utf8").split("\n");
    const end = lines.indexOf("---", 1);
    return lines[0] === "---" && end > 0 && lines[end + 1] === "" && lines[end + 2] === markerLine;
  } catch {
    return false;
  }
}

/** Leftovers of a session that died: the marked files of `dir` are removed at the next launch. */
export function sweepAgentFiles({ dir, fsApi = fs }) {
  let entries;
  try {
    entries = fsApi.readdirSync(dir);
  } catch {
    return [];
  }
  const removed = [];
  for (const name of entries.filter((entry) => entry.endsWith(".md"))) {
    const file = path.join(dir, name);
    if (isOurs(fsApi, file)) {
      fsApi.rmSync(file, { force: true });
      removed.push(file);
    }
  }
  return removed;
}
